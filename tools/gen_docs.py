"""Write the reference pages in docs/ from a catalog made by extract.py.

usage: python -I tools/gen_docs.py <catalog.json> <docs-dir>
"""
import sys, os, json, collections

CAT, OUT = sys.argv[1], sys.argv[2]
c = json.load(open(CAT, encoding='utf-8'))
os.makedirs(OUT, exist_ok=True)

# app id -> launcher flow file (flow/<file>.ymt); the pairing is by name, the game keeps it in code
APP_FLOW = {
    'abilities': 'abilities_launcher_flow', 'character_creator': 'character_creator', 'collectors': 'collectors_launcher_flow',
    'coupons': 'coupons_launcher_flow', 'crafting': 'crafting_launcher_flow', 'ending_credits': 'end_credits_launcher_flow',
    'fast_travel_menu': 'fast_travel_launcher_flow', 'help_menu': 'help_launcher_flow', 'hub': 'hub_launcher_flow',
    'hud_quick_select': 'hud_quick_select_launcher_flow', 'map': 'map_launcher_flow', 'mp_mission_info': 'mp_mission_info',
    'naturalist': 'naturalist_launcher_flow', 'opening_credits_sequence': 'opening_credits_flow', 'pause_menu': 'pause_main_flow',
    'player_menu': 'pm_launcher_flow', 'rewards': 'rewards_launcher_flow', 'role_progression': 'role_progression_launcher_flow',
    'satchel': 'satchel_launcher_flow', 'settings_menu': 'settings_launcher_flow', 'shop_browsing': 'shop_browsing_main_flow',
    'stats_menu': 'stats_launcher_flow', 'trader': 'trader_launcher_flow', 'translation_overlay': 'translate_launcher_flow',
    'weapon_locker': 'weapon_locker_launcher_flow', 'leaderboards': 'leaderboard_and_post_match_launcher',
}
# apps whose launcher is found by flow block id rather than file name
APP_FLOW_ID = {
    'landing_page': 'landing_flow', 'store': 'store_launcher_flow', 'shop_menu': 'shop_launcher_flow',
    'saveload_menu': 'savegame_launcher_flow', 'virtual_keyboard': 'on_screen_keyboard', 'lobbies_menu': 'pm_flow_lobby_launcher',
}


def joaat(s):
    h = 0
    for ch in s.lower().encode('utf-8'):
        h = (h + ch) & 0xFFFFFFFF
        h = (h + (h << 10)) & 0xFFFFFFFF
        h ^= h >> 6
    h = (h + (h << 3)) & 0xFFFFFFFF
    h ^= h >> 11
    h = (h + (h << 15)) & 0xFFFFFFFF
    return h


def hs(s):
    h = joaat(s)
    return '`0x%08X` / `%d`' % (h, h - 0x100000000 if h >= 0x80000000 else h)


def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def write(name, title, intro, body):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# {title}\n\n{intro}\n\n> Generated by `tools/gen_docs.py` from the game files. Do not edit by hand.\n\n{body}\n')


by_file = {f['file'].replace('flow/', '', 1): f for f in c['flows'].values()}
kids = {}
for f in c['flows'].values():
    ks = set()
    for n in f['subflows'] + f['resources']:
        k = by_file.get(n)
        if k and k['id'] != f['id']:
            ks.add(k['id'])
    kids[f['id']] = ks


def reach(fid):
    seen, st = set(), [fid]
    while st:
        x = st.pop()
        if x in seen:
            continue
        seen.add(x)
        st.extend(kids.get(x, ()))
    return [c['flows'][i] for i in seen]


# ---------- apps ----------
lines = []
for app in sorted(c['apps']):
    f = by_file.get(APP_FLOW.get(app, '')) or c['flows'].get(app) or c['flows'].get(APP_FLOW_ID.get(app, ''))
    lines.append(f'## `{app}`\n')
    lines.append(f'- Hash: {hs(app)}')
    lines.append(f"- Launcher flow: {'`' + f['id'] + '` (`' + f['file'] + '`)' if f else 'started by code, no flow file'}")
    if c['apps'][app]['blockedBy']:
        lines.append('- Cannot launch while open: ' + ', '.join(f'`{b}`' for b in c['apps'][app]['blockedBy']))
    if f:
        flows = reach(f['id'])
        ents = [(x['id'], e) for x in flows for e in x['entries']]
        if ents:
            lines.append('\n| Entry | Hash for `LaunchUiappByHashWithEntry` | In flow | Goes to |\n|---|---|---|---|')
            for fid, e in ents:
                lines.append(f"| `{e['id']}` | {hs(e['id'])} | `{fid}` | `{cell(e.get('target') or '')}` |")
        ch = sorted({e['channel'] for x in flows for e in x['events']})
        if ch:
            lines.append('\nEvent channels from its flows: ' + ', '.join(f'`{x}`' for x in ch))
        sc = sorted({s for x in flows for s in x['scenes']})
        if sc:
            lines.append('\nScenes: ' + ', '.join(f'`{s}`' for s in sc[:40]) + (f' and {len(sc) - 40} more' if len(sc) > 40 else ''))
    lines.append('')
write('apps.md', 'UI apps',
      'The app ids `LaunchUiappByHash` accepts (from `data/ui/applaunch/launchconditions.ymt`), the flow each one starts, '
      'and the entry points of that flow. An entry\'s hash is the second argument of `LaunchUiappByHashWithEntry` '
      'and of `_UIFLOWBLOCK_ENTER`.', '\n'.join(lines))

# ---------- flows ----------
lines = ['| Flow block | File | Entries | Scenes | List templates |', '|---|---|---|---|---|']
for f in sorted(c['flows'].values(), key=lambda x: x['id']):
    lines.append(f"| `{f['id']}`<br>{hs(f['id'])} | `{f['file']}` | {', '.join('`' + e['id'] + '`' for e in f['entries'])} | "
                 f"{', '.join('`' + s + '`' for s in f['scenes'][:6])}{' …' if len(f['scenes']) > 6 else ''} | {len(f['templates']) or ''} |")
write('flows.md', 'Flow blocks',
      'Every `rage::fwuiFlowBlock` in `data/ui/flow`. A script can host any of them without its app:\n\n'
      '```lua\nlocal block = Citizen.InvokeNative(0xC0081B34E395CE48, `pm_flow_weapon_inspect`) -- _UIFLOWBLOCK_REQUEST\n'
      'while not Citizen.InvokeNative(0x10A93C057B6BD944, block) do Wait(0) end   -- _UIFLOWBLOCK_IS_LOADED\n'
      'Citizen.InvokeNative(0x3B7519720C9DCB45, block, 0)                          -- _UIFLOWBLOCK_ENTER, entry hash or 0\n'
      'Citizen.InvokeNative(0x4C6F2C4B7A03A266, `my_ui`, block)                  -- UI_STATE_MACHINE_CREATE\n'
      '-- later: Citizen.InvokeNative(0x4EB122210A90E2D8, `my_ui`)              -- UI_STATE_MACHINE_DESTROY\n```', '\n'.join(lines))

# ---------- events ----------
lines = []
for ch in sorted(c['events']):
    e = c['events'][ch]
    lines.append(f'## `{ch}` — {hs(ch)}\n')
    lines.append('| Parameter (offset 16) | Hash | Type | Sent from |\n|---|---|---|---|')
    for p, v in sorted(e['params'].items()):
        lines.append(f"| `{p}` | {hs(p) if p != '(none)' else ''} | {', '.join(t.replace('UISCRIPTEVENTTYPE_', '') for t in v['types']) or 'ITEM_SELECTED'} | "
                     f"{', '.join('`' + s + '`' for s in v['sources'][:3])}{' …' if len(v['sources']) > 3 else ''} |")
    lines.append('')
write('events.md', 'UI events',
      'Events the UI posts for scripts: `ScriptEventOp` behaviours on screen elements and event states in flows. '
      'Poll the channel with `EventsUiIsPending(channel)` and read it with `EVENTS_UI_GET_MESSAGE` (`0xE24E957294241444`): '
      'the event type is at offset 0, the parameter hash at 16 and the item\'s data container at 24.', '\n'.join(lines))

# ---------- templates ----------
lines = ['| Alias | Hash | Widget | Registered by flow | Keys |', '|---|---|---|---|---|']
seen = set()
for t in sorted(c['templates'], key=lambda x: (x['alias'], x['flow'])):
    k = (t['alias'], t['widget'])
    if k in seen:
        continue
    seen.add(k)
    flows = sorted({x['flow'] for x in c['templates'] if (x['alias'], x['widget']) == k})
    lines.append(f"| `{t['alias']}` | {hs(t['alias'])} | `{t['widget']}` | {', '.join('`' + f + '`' for f in flows[:4])}{' …' if len(flows) > 4 else ''} | {', '.join(t['keys'])} |")
write('templates.md', 'List item templates',
      'The aliases flows register for their item lists. Pass one to '
      '`DatabindingInsertUiItemToListFromContextStringAlias(list, -1, alias, itemContainer)` while that flow runs; '
      'the item container\'s values fill the widget. The same alias is also an `Instancing` type inside screens.', '\n'.join(lines))

# ---------- HUD ----------
lines = ['| Context | Hash | Shows | Hides |', '|---|---|---|---|']
for k in sorted(c['hudcontexts']):
    v = c['hudcontexts'][k]
    lines.append(f"| `{k}` | {hs(k)} | {', '.join(sorted(set(x.replace('HUD_VISIBILITY_SLOT_', '') for x in v['shows'])))} | "
                 f"{', '.join(sorted(set(x.replace('HUD_VISIBILITY_SLOT_', '') for x in v['hides'])))} |")
lines += ['', '## Slots', '', '| Slot | Shown by | Script args that hide it |', '|---|---|---|']
for s in c['hudslots']:
    if s['slot']:
        lines.append(f"| {'&nbsp;' * 2 * s['depth']}`{s['slot']}` | {', '.join('`' + x + '`' for x in s['showCtx'] if x.strip())} | {', '.join('`' + a + '`' for a in s['args'])} |")
write('hud.md', 'HUD contexts and slots',
      'From `data/ui/hudvisibility/visibilityconditions.ymt`. The HUD is a tree of slots; each `HUD_CTX_*` context hides or shows slots. '
      'Turn one on with `_ENABLE_HUD_CONTEXT` (`0x4CC5F2FC1332577F`) and off with `_DISABLE_HUD_CONTEXT` (`0x8BC7C1F929D07BF3`). '
      'A HUD widget whose slot is hidden by default appears only once a context that shows its slot is on — '
      'the money HUD needs `HUD_CTX_TITHING`, which shows `CAMP_SUPPLY`.', '\n'.join(lines))

# ---------- datastore ----------
def typ(p, m):
    last = p.split('.')[-1]
    if 'context' in m:
        return 'list / container'
    if 'anim' in m and not {'RawText', 'Text'} & set(m):
        return 'int'
    if any(x in m for x in ('RawText', 'Rawtext', 'setTimeAsString', 'Texture', 'TextureDictionary')):
        return 'string'
    if any(x in m for x in ('Text', 'Color', 'FillColor', 'TrackColor', 'Style', 'IconToken')):
        return 'hash'
    if any(x in m for x in ('Visible', 'Enabled', 'FlipHorizontal', 'FlipVertical', 'Renderable')):
        return 'bool'
    return 'int'


groups = collections.defaultdict(list)
for p, d in c['datastore'].items():
    if p and not p.startswith('^'):
        groups[p.split('.')[0]].append((p, d))
lines = []
for root in sorted(groups, key=str.lower):
    lines.append(f'## `{root}`\n\n| Path | Type | Bound to | Read by |\n|---|---|---|---|')
    for p, d in sorted(groups[root]):
        ref = d['refs'][0].split(' > ')[0] if d['refs'] else ''
        lines.append(f"| `{p}` | {typ(p, d['members'])} | {', '.join(d['members'])} | `{ref}`{' +' + str(len(d['refs']) - 1) if len(d['refs']) > 1 else ''} |")
    lines.append('')
write('datastore.md', 'DataBinding paths',
      'Every absolute path under `ScriptDatastoreRoot` that a screen or widget reads, including the ones reached through a binding '
      'context. Create the first segment with `DatabindingAddDataContainerFromPath("", root)` and the rest with '
      '`DatabindingAddDataContainer`. The type is inferred from what the UI binds the value to: `RawText` takes a string, '
      '`Text` a label hash, `Visible` a bool, `Value`/`Minimum`/`Maximum` a number.', '\n'.join(lines))

print('apps', len(c['apps']), 'flows', len(c['flows']), 'channels', len(c['events']), 'templates', len(seen),
      'contexts', len(c['hudcontexts']), 'paths', sum(len(v) for v in groups.values()))
